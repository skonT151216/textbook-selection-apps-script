const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { browserFixture } = require('./browser-fixture.cjs');
const { clone } = require('./identity-fixture.cjs');
(async () => {
  const f = await browserFixture(), { page, env } = f;
  const before = clone(env.api.testRead().data), calls = [], output = path.join(__dirname, '..', 'tmp', 'r17-qa');
  fs.mkdirSync(output, { recursive: true });
  let tag = 'v2026.10.09.4', offline = false;
  env.context.UrlFetchApp = { fetch(url) { calls.push(url); if (offline) throw Error('offline'); return { getResponseCode: () => 200, getContentText: () => JSON.stringify({ tag_name: tag }) }; } };
  const expire = () => env.cache.delete('textbook-selection-latest-release-v2');
  page.setDefaultTimeout(12000);
  try {
    await page.getByLabel('사용 중인 프로그램 버전').getByText('프로그램 버전 v2026.10.09.3', { exact: true }).waitFor();
    assert.equal(calls.length, 0, 'login page displays server version without release queries');
    await f.login('manager');
    await page.getByText('새 버전 v2026.10.09.4이 나왔습니다.', { exact: true }).waitFor();
    assert.equal(await page.locator('.program-update-banner a').getAttribute('href'), 'https://github.com/skonT151216/textbook-selection-apps-script/releases/latest');
    await page.getByText(/자동 업데이트는 아닙니다/).waitFor();
    const panel = await page.locator('.program-update-panel').boundingBox();
    const sidebar = await page.locator('.side').boundingBox();
    assert.ok(panel.x >= sidebar.x + sidebar.width, 'desktop navigation never covers the update panel');
    await page.screenshot({ path: path.join(output, 'manager-update.png'), fullPage: false });
    await page.setViewportSize({ width: 390, height: 844 });
    const mobile = await page.locator('.program-update-panel').boundingBox();
    assert.ok(mobile.x >= 0 && mobile.x + mobile.width <= 390, 'mobile banner stays within the viewport');
    await page.screenshot({ path: path.join(output, 'manager-mobile.png'), fullPage: false });
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.getByRole('button', { name: '나중에 보기', exact: true }).click();
    assert.equal(await page.locator('.program-update-banner').count(), 0);
    await page.reload();
    await page.getByRole('button', { name: '업데이트 확인', exact: true }).waitFor();
    assert.equal(await page.locator('.program-update-banner').count(), 0, 'dismissed release stays hidden for this session');
    await page.getByRole('button', { name: '업데이트 확인', exact: true }).click();
    await page.locator('.program-update-banner').waitFor();
    assert.equal(calls.length, 1, 'manual repeated clicks reuse the one-minute server cache');
    tag = 'v2026.10.09.5'; expire();
    await page.getByRole('button', { name: '업데이트 확인', exact: true }).click();
    await page.getByText('새 버전 v2026.10.09.5이 나왔습니다.', { exact: true }).waitFor();
    tag = 'v2026.10.09.6'; expire();
    await page.evaluate(() => { window.__r17Now = Date.now; Date.now = () => window.__r17Now() + 3600001; document.dispatchEvent(new Event('visibilitychange')); });
    await page.getByText('새 버전 v2026.10.09.6이 나왔습니다.', { exact: true }).waitFor();
    await page.evaluate(() => { Date.now = window.__r17Now; delete window.__r17Now; });
    tag = 'v2026.10.09.3'; expire();
    await page.getByRole('button', { name: '업데이트 확인', exact: true }).click();
    await page.getByText('새 업데이트가 없습니다.', { exact: true }).waitFor();
    assert.equal(await page.locator('.program-update-banner').count(), 0);
    offline = true; expire();
    await page.getByRole('button', { name: '업데이트 확인', exact: true }).click();
    await page.getByText('업데이트를 확인하지 못했습니다. 잠시 후 다시 확인해 주세요.', { exact: true }).waitFor();
    await page.screenshot({ path: path.join(output, 'manager-offline.png'), fullPage: false });
    await page.getByRole('button', { name: /개인별 평가/ }).first().click();
    await page.locator('.evaluation-sheet').waitFor();
    assert.equal(await page.locator('.evaluation-sheet .app-version-bar, .evaluation-sheet .program-update-panel').count(), 0, 'version notices never enter PDF-captured forms');
    await page.emulateMedia({ media: 'print' });
    assert.equal(await page.locator('.app-version-bar').isVisible(), false);
    assert.equal(await page.locator('.program-update-panel').isVisible(), false);
    await page.emulateMedia({ media: 'screen' });
    await page.getByRole('button', { name: '로그아웃', exact: true }).click();
    const count = calls.length;
    await f.login('kim1');
    await page.getByRole('button', { name: /개인별 평가/ }).first().waitFor();
    await page.getByLabel('사용 중인 프로그램 버전').waitFor();
    assert.equal(await page.locator('.program-update-panel').count(), 0, 'teachers see the version but not manager update controls');
    assert.equal(calls.length, count, 'teachers never query external releases');
    assert.deepEqual(clone(env.api.testRead().data), before);
    assert.ok(f.requests.every(request => request.method !== 'PUT' && request.path !== '/api/setup'), 'version UI never triggers workspace/setup writes');
    assert.deepEqual(f.errors, []);
    console.log('r17 browser passed: public server version, manager banner/refresh/dismiss/current/offline, teacher isolation, print exclusion, no workspace writes or browser errors');
  } finally { await f.close(); }
})().catch(error => { console.error(error.message, error.stack.split('\n').filter(line => /^\s+at /.test(line)).slice(0, 3).join('\n')); process.exitCode = 1; });
